// Run: node scripts/build-airports.mjs
import fs from 'node:fs/promises'
import path from 'node:path'

const OPENFLIGHTS_URL = 'https://raw.githubusercontent.com/jpatokal/openflights/master/data/airports.dat'
const OUT = path.resolve('src/lib/airports.ts')

async function main() {
  console.log('Downloading OpenFlights airports.dat...')
  const resp = await fetch(OPENFLIGHTS_URL)
  if (!resp.ok) throw new Error(`Download failed: ${resp.status}`)
  const text = await resp.text()

  const rows = text.split('\n').filter(Boolean)
  console.log(`Parsing ${rows.length} rows...`)

  const airports = []

  for (const line of rows) {
    // OpenFlights CSV: ID,Name,City,Country,IATA,ICAO,Lat,Lon,Alt,...
    const parts = line.match(/(".*?"|[^,]+)(?=,|$)/g)
    if (!parts || parts.length < 9) continue

    const clean = (s) => s?.replace(/^"|"$/g, '').trim() ?? ''

    const name = clean(parts[1])
    const city = clean(parts[2])
    const country = clean(parts[3])
    const iata = clean(parts[4])
    const icao = clean(parts[5])
    const lat = parseFloat(clean(parts[6]))
    const lon = parseFloat(clean(parts[7]))
    
    // Index 8 is Altitude
    const altStr = clean(parts[8])
    const alt = parseInt(altStr, 10) || 0

    if (!icao || icao.length !== 4) continue
    if (!iata || iata.length !== 3) continue
    if (Number.isNaN(lat) || Number.isNaN(lon)) continue
    if (icao === '\\N' || iata === '\\N') continue

    airports.push({
      icao: icao.toUpperCase(),
      iata,
      name,
      city: city || '—',
      country: country || '—',
      lat,
      lon,
      alt, // Added real elevation
    })
  }

  // Deduplicate
  const seen = new Set()
  const unique = airports.filter((a) => {
    if (seen.has(a.icao)) return false
    seen.add(a.icao)
    return true
  })

  unique.sort((a, b) => a.country.localeCompare(b.country) || a.name.localeCompare(b.name))

  console.log(`Writing ${unique.length} airports to ${OUT}`)

  const body = `// AUTO-GENERATED by scripts/build-airports.mjs — do not edit by hand.
// Source: OpenFlights (ODbL) — https://openflights.org/data

export interface Airport {
  icao: string
  iata: string
  name: string
  city: string
  country: string
  lat: number
  lon: number
  alt: number
}

export const AIRPORTS: Airport[] = ${JSON.stringify(unique, null, 2)}

export function searchAirports(query: string): Airport[] {
  const q = query.toUpperCase().trim()
  if (!q) return AIRPORTS.slice(0, 50)
  return AIRPORTS.filter(
    (a) =>
      a.icao.includes(q) ||
      a.iata.includes(q) ||
      a.name.toUpperCase().includes(q) ||
      a.city.toUpperCase().includes(q) ||
      a.country.toUpperCase().includes(q)
  ).slice(0, 100)
}

export function getAirport(icao: string): Airport | undefined {
  return AIRPORTS.find((a) => a.icao === icao.toUpperCase())
}

/** Find the nearest airport to a coordinate. Returns undefined if none within ~55 km. */
export function nearestAirport(lat: number, lon: number): Airport | undefined {
  let best: Airport | undefined
  let bestDist = Infinity
  for (const a of AIRPORTS) {
    const dLat = a.lat - lat
    const dLon = a.lon - lon
    const d = dLat * dLat + dLon * dLon
    if (d < bestDist) {
      bestDist = d
      best = a
    }
  }
  if (bestDist > 0.25) return undefined
  return best
}
`

  await fs.writeFile(OUT, body, 'utf8')
  console.log('Done.')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})